/** 臺灣史、中國史、世界史：講義的三欄 */
export type Track = "tw" | "cn" | "world";

/**
 * 講義裡標出的重點事件。標題與說明依講義內容改寫成孩子看得懂的短句；
 * 地點是講義沒寫的，由我們標在事件發生地（地球上註明「位置示意」）。
 * 網站年表裡已經有同一件事時（`match` 關鍵字＋年份相差一年內），就直接把那一條標成重點，不重複新增。
 */
export interface KeyEvent {
  id: string;
  track: Track;
  start: AstronomicalYear;
  end?: AstronomicalYear;
  /** 年代只知道大約（例如「約西元前 6 世紀」） */
  circa?: boolean;
  title: string;
  note?: string;
  place: string;
  lat: number;
  lon: number;
  /** 對應的「基本架構」條目（periods.ts 的 title） */
  theme?: string;
  /** 用來找網站年表裡同一件事的關鍵字 */
  match?: string[];
}

type Opts = Partial<Pick<KeyEvent, "end" | "circa" | "note" | "theme" | "match">>;

let n = 0;
const k = (track: Track, start: AstronomicalYear, title: string, place: string, lat: number, lon: number, opts: Opts = {}): KeyEvent => ({
  id: `key-${track}-${++n}`,
  track,
  start,
  title,
  place,
  lat,
  lon,
  ...opts,
});
const w = (...a: Parameters<typeof k> extends [Track, ...infer R] ? R : never) => k("world", ...a);
const tw = (...a: Parameters<typeof k> extends [Track, ...infer R] ? R : never) => k("tw", ...a);
const cn = (...a: Parameters<typeof k> extends [Track, ...infer R] ? R : never) => k("cn", ...a);

